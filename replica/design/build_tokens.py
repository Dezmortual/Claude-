#!/usr/bin/env python3
"""Generate tokens.css and tailwind.preset.cjs from tokens.json. Standard library only.

    python3 replica/design/build_tokens.py

Rerun after every token change (including /replica-brand), then run contrast.py.
Components use the Tailwind names (bg-surface, text-muted, rounded-md), never hex.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE / "tokens.json").read_text())


def rgb(hex_):
    h = hex_.lstrip("#")
    return "%d %d %d" % tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


light = {k: v for k, v in T["color"].items() if isinstance(v, str)}
dark = T["color"]["dark"]
assert set(light) == set(dark), "light and dark need the same roles: %s" % (set(light) ^ set(dark))


def colour_vars(cols):
    # Space-separated channels so Tailwind opacity modifiers work: bg-accent/10
    return "\n".join("  --c-%s: %s;" % (k, rgb(v)) for k, v in cols.items())


lines = ["/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */", ":root {",
         colour_vars(light)]
lines += ["  --font-sans: %s;" % T["font"]["sans"], "  --font-mono: %s;" % T["font"]["mono"]]
for k, t in T["type"].items():
    lines.append("  --text-%s: %dpx; --leading-%s: %dpx; --weight-%s: %d;" % (
        k, t["size"], k, t["line"], k, t["weight"]))
for i, s in enumerate(T["space"]):
    lines.append("  --space-%d: %dpx;" % (i, s))
for k, r in T["radius"].items():
    lines.append("  --radius-%s: %dpx;" % (k, r))
for k, s in T["shadow"].items():
    lines.append("  --shadow-%s: %s;" % (k, s))
for k, m in T["motion"].items():
    lines.append("  --motion-%s: %s;" % (k, m))
for k, v in T["layout"].items():
    if isinstance(v, (int, float)):
        lines.append("  --layout-%s: %dpx;" % (k, v))
for k, v in T["z"].items():
    lines.append("  --z-%s: %d;" % (k, v))
lines += ["  color-scheme: light;", "}", "",
          "/* Dark: follows the OS unless the user picked light; [data-theme=dark] forces it. */",
          "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {",
          colour_vars(dark).replace("\n  ", "\n    ").replace("  --", "    --", 1),
          "    color-scheme: dark;", "  }", "}",
          ":root[data-theme=\"dark\"] {", colour_vars(dark), "  color-scheme: dark;", "}", "",
          "html { background: rgb(var(--c-bg)); color: rgb(var(--c-text)); font-family: var(--font-sans);",
          "  font-size: var(--text-base); line-height: var(--leading-base); -webkit-font-smoothing: antialiased; }",
          "/* Prices, % changes and table figures line up. */",
          ".num, td, .tabular { font-variant-numeric: tabular-nums; }",
          ":focus-visible { outline: 2px solid rgb(var(--c-focus)); outline-offset: 2px; }",
          "@media (prefers-reduced-motion: reduce) { *, *::before, *::after {",
          "  animation-duration: 1ms !important; transition-duration: 1ms !important; } }", ""]
(HERE / "tokens.css").write_text("\n".join(lines))

preset = {
    "darkMode": ["selector", "[data-theme=\"dark\"]"],
    "theme": {
        "colors": dict({k: "rgb(var(--c-%s) / <alpha-value>)" % k for k in light},
                       transparent="transparent", current="currentColor", white="#ffffff"),
        "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
        "fontSize": {k: ["%dpx" % t["size"], {"lineHeight": "%dpx" % t["line"], "fontWeight": str(t["weight"])}]
                     for k, t in T["type"].items()},
        "spacing": dict({"px": "1px"}, **{str(s // 4 if s % 4 == 0 else s / 4): "%dpx" % s for s in T["space"]}),
        "borderRadius": dict({"none": "0"}, **{k: "%dpx" % r for k, r in T["radius"].items()}),
        "boxShadow": dict({"none": "none"}, **T["shadow"]),
        "screens": {k: "%dpx" % v for k, v in T["layout"]["breakpoints"].items()},
        "extend": {
            # text-fg / text-muted / text-subtle instead of text-text-muted; plain `border` is the border role.
            "textColor": {"fg": "rgb(var(--c-text) / <alpha-value>)",
                          "muted": "rgb(var(--c-text-muted) / <alpha-value>)",
                          "subtle": "rgb(var(--c-text-subtle) / <alpha-value>)"},
            "borderColor": {"DEFAULT": "rgb(var(--c-border) / <alpha-value>)",
                            "input": "rgb(var(--c-border-input) / <alpha-value>)"},
            "ringColor": {"DEFAULT": "rgb(var(--c-focus) / <alpha-value>)"},
            "maxWidth": {k: "%dpx" % T["layout"][k] for k in ("content", "wide", "prose")},
            "height": {"header": "%dpx" % T["layout"]["header"], "row": "%dpx" % T["layout"]["table-row"],
                       "row-compact": "%dpx" % T["layout"]["table-row-compact"]},
            "minHeight": {"tap": "%dpx" % T["layout"]["tap-target"]},
            "minWidth": {"tap": "%dpx" % T["layout"]["tap-target"]},
            "transitionDuration": {k: v for k, v in T["motion"].items() if k != "ease"},
            "transitionTimingFunction": {"DEFAULT": T["motion"]["ease"]},
            "zIndex": {k: str(v) for k, v in T["z"].items()},
        },
    },
}
(HERE / "tailwind.preset.cjs").write_text(
    "// Generated by build_tokens.py from tokens.json. Do not edit by hand.\n"
    "// Web: presets: [require('./replica/design/tailwind.preset.cjs')]. Mobile: same file via NativeWind.\n"
    "module.exports = " + json.dumps(preset, indent=2) + ";\n")
print("wrote tokens.css, tailwind.preset.cjs (%d colour roles, light + dark)" % len(light))
