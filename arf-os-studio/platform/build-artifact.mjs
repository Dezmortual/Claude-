// Builds artifact.html, the entry page used when publishing the platform as a Claude artifact:
// index.html without the document skeleton (the publisher adds it) and with the stylesheet inlined.
// Run: node build-artifact.mjs
import fs from "node:fs";
const html = fs.readFileSync(new URL("./index.html", import.meta.url), "utf8");
const css = fs.readFileSync(new URL("./css/app.css", import.meta.url), "utf8");
const head = html.split("<head>")[1].split("</head>")[0];
const body = html.split("<body>")[1].split("</body>")[0].trim();
const keep = head.split("\n").map(l => l.trim()).filter(l => /^<(title|meta name="description"|link rel="(preconnect|icon)"|link rel="stylesheet" href="https:)/.test(l));
const out = `<title>${head.match(/<title>(.*?)<\/title>/)[1]}</title>\n<style>\n${css}</style>\n${keep.filter(l => !l.startsWith("<title")).join("\n")}\n<!-- Generated by build-artifact.mjs from index.html; do not edit by hand. -->\n${body}\n`;
fs.writeFileSync(new URL("./artifact.html", import.meta.url), out);
console.log("artifact.html", out.length, "bytes");
